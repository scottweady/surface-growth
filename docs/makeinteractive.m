% MAKEINTERACTIVE  Data for the interactive sphere-growth widget on the docs page.
%
% Solves the axisymmetric growth trajectory on the sphere of radius R = 10
% (as in Fig. 3a) for a range of sensitivities lambda, from area 4*pi until
% the colony covers 99.5% of the sphere, and writes
%   docs/assets/sphere-growth.js
% which defines window.SPHERE_GROWTH = { R, A0, s, lambdas, runs, algae }.
% Each run holds, on a uniform time grid, the time t, cap angle H, total
% growth rate |dOmega/dt| and the pointwise growth rate gamma = exp(-lambda p)
% at the fractions s = eta/H of the cap angle (clustered towards the edge,
% where the boundary layer forms at large lambda). gamma is stored as base64
% bytes, round(255*gamma), time-major with s varying fastest; gammaMin is the
% (unquantized) value at the pole, where gamma is smallest. (A .js file rather
% than JSON so the page also works when opened from disk.)
%
% Run from the repository root after setup.

here = fileparts(mfilename('fullpath'));
root = fileparts(here);
addpath(fullfile(root, 'utils'), fullfile(root, 'src'))

R = 10;
N = 100;
A0 = 4 * pi;
coverFinal = 0.995;                   % stop at this fraction of the sphere
nH = 1500;                            % cap angles at which dH/dt is solved
nOut = 120;                           % time samples per trajectory in the output
nS = 48;                              % samples of gamma along the cap
s = sin(pi/2 * linspace(0, 1, nS));   % eta/H, clustered towards the edge

lambdas = [0, 10.^linspace(-2, 1, 19)];

H0 = acos(1 - A0 / (2 * pi * R^2));
Hf = acos(1 - 2 * coverFinal);
Hgrid = linspace(H0, Hf, nH)';

% Integrate t(H) = int dH / (dH/dt) rather than stepping in time: for small
% lambda the cap accelerates so much near the far pole that a fixed time step
% overshoots H = pi.
runs = cell(numel(lambdas), 1);
for k = 1:numel(lambdas)
  lambda = lambdas(k);
  fprintf('lambda = %.4g (%d/%d)\n', lambda, k, numel(lambdas))

  U = arrayfun(@(H) growthSphere(H, lambda, R, N), Hgrid);   % dH/dt
  T = cumtrapz(Hgrid, 1 ./ U);

  ts = linspace(0, T(end), nOut)';
  Hs = interp1(T, Hgrid, ts, 'pchip');
  rate = zeros(nOut, 1);
  gam = zeros(nOut, nS);
  for j = 1:nOut
    [Uj, p, h] = growthSphere(Hs(j), lambda, R, N);
    rate(j) = 2 * pi * R^2 * sin(Hs(j)) * Uj;          % d|Omega|/dt
    gam(j, :) = exp(-lambda * interp1(h, p, s * Hs(j), 'pchip'));
  end

  gamBytes = uint8(round(255 * reshape(gam.', 1, [])));   % time-major, s fastest
  runs{k} = struct('lambda', lambda, ...
                   't', round(ts, 4), ...
                   'H', round(Hs, 5), ...
                   'rate', round(rate, 4), ...
                   'gammaMin', round(gam(:, 1), 6), ...
                   'gamma', matlab.net.base64encode(gamBytes));
end

out = struct('R', R, 'A0', A0, 's', round(s, 5), 'lambdas', lambdas, ...
             'runs', {runs}, 'algae', round(cmocean('algae', 32), 4));

fid = fopen(fullfile(here, 'assets', 'sphere-growth.js'), 'w');
fprintf(fid, ['// Generated by docs/makeinteractive.m: growth on the sphere R = 10 ' ...
              'for a range of lambda.\n']);
fprintf(fid, 'window.SPHERE_GROWTH = %s;\n', jsonencode(out));
fclose(fid);


% ── Area against time on spheres of different radii (Fig. 3(b), live) ────────
% As scripts/sphereGrowth.m, for every lambda of the interactive Fig. 3(a):
% the area |Omega|/|Omega_0| against time from |Omega_0| = 4 pi to 400 pi on
% spheres of radius R = 12, 14, 18, 26, 42, and in the planar limit
% R -> infinity (edge speed in closed form). R = 10 is the trajectory already
% stored for Fig. 3(a). Writes docs/assets/sphere-radii.js defining
% window.SPHERE_RADII = { R, lambdas, curves, planar }, with curves{l}{r} and
% planar{l} each holding t and area.

Rb = 10 + 2.^(1:5);
Af = 400 * pi;
nB = 80;                                          % samples per curve in the output
curves = cell(numel(lambdas), 1);
planar = cell(numel(lambdas), 1);
for l = 1:numel(lambdas)
  lambda = lambdas(l);
  fprintf('Fig. 3(b) curves, lambda = %.4g (%d/%d)\n', lambda, l, numel(lambdas))
  cl = cell(numel(Rb), 1);
  for r = 1:numel(Rb)
    R = Rb(r);
    Hg = linspace(acos(1 - A0 / (2 * pi * R^2)), acos(1 - Af / (2 * pi * R^2)), 800)';
    U = arrayfun(@(H) growthSphere(H, lambda, R, N), Hg);
    T = cumtrapz(Hg, 1 ./ U);
    ts = linspace(0, T(end), nB)';
    A = 2 * pi * R^2 * (1 - cos(interp1(T, Hg, ts, 'pchip'))) / A0;
    cl{r} = struct('t', round(ts, 4), 'area', round(A, 4));
  end
  curves{l} = cl;

  % plane: disk of radius rho, d rho/dt = 32 c^2 rho / (1 - 8 c^2 lambda rho^2)
  rho = linspace(sqrt(A0 / pi), sqrt(Af / pi), 2000)';
  if lambda == 0
    F = rho / 2;
  else
    c = (sqrt(1 + lambda * rho.^2 / 2) - 1) ./ (2 * lambda * rho.^2);
    F = 32 * c.^2 .* rho ./ (1 - 8 * c.^2 * lambda .* rho.^2);
  end
  T = cumtrapz(rho, 1 ./ F);
  ts = linspace(0, T(end), nB)';
  A = pi * interp1(T, rho, ts, 'pchip').^2 / A0;
  planar{l} = struct('t', round(ts, 4), 'area', round(A, 4));
end
out = struct('R', Rb, 'lambdas', lambdas, 'curves', {curves}, 'planar', {planar});
fid = fopen(fullfile(here, 'assets', 'sphere-radii.js'), 'w');
fprintf(fid, '// Generated by docs/makeinteractive.m: area against time on spheres of several radii.\n');
fprintf(fid, 'window.SPHERE_RADII = %s;\n', jsonencode(out));
fclose(fid);


% ── Growth rate against cap angle (interactive Fig. 4) ───────────────────────
% For each lambda of Fig. 4(b), the growth rate |dOmega/dt| as a function of
% the cap angle H on the sphere R = 10, normalized by its maximum, as in
% scripts/sphereGrowthRate.m. H*(lambda) is taken from the committed
% data/fig4.mat so panel (b) is exactly the paper's curve. Writes
%   docs/assets/sphere-rate.js
% defining window.SPHERE_RATE = { H, lambdas, Hstar, rates, ref }, where
% rates(k, :) is the normalized curve for lambdas(k) and ref holds the
% curves of Fig. 4(a) (lambda = 0, 0.01, 0.1, 1).

S = load(fullfile(root, 'data', 'fig4.mat'), 'AsaveAll', 'Amax');
L4 = S.Amax(:, 1)';
Hstar = S.Amax(:, 2)';

Hr = linspace(1e-2, pi - 1e-2, 160);      % H range of sphereGrowthRate.m, finer
rates = zeros(numel(L4), numel(Hr));
for k = 1:numel(L4)
  fprintf('rate curve lambda = %.3f (%d/%d)\n', L4(k), k, numel(L4))
  dA = arrayfun(@(H) 2 * pi * R^2 * sin(H) * growthSphere(H, L4(k), R, N), Hr);
  rates(k, :) = dA / max(dA);
end

ref = cellfun(@(A) struct('H', round(A(:, 1)', 4), 'rate', round(A(:, 2)' / max(A(:, 2)), 4)), ...
              S.AsaveAll, 'UniformOutput', false);

out = struct('H', round(Hr, 5), 'lambdas', round(L4, 6), 'Hstar', round(Hstar, 5), ...
             'rates', round(rates, 4), 'ref', {ref}, 'refLambdas', [0 0.01 0.1 1]);
fid = fopen(fullfile(here, 'assets', 'sphere-rate.js'), 'w');
fprintf(fid, '// Generated by docs/makeinteractive.m: normalized growth rate against cap angle, R = 10.\n');
fprintf(fid, 'window.SPHERE_RATE = %s;\n', jsonencode(out));
fclose(fid);


% ── Homogenized growth on periodic surfaces (interactive Fig. 5) ─────────────
% For the one-dimensional wave h = a sin(2 pi xi') at amplitudes a in [0, 1],
% the homogenized solution on the disk (lambda = 1) as in
% scripts/roughnessGrowthRate.m: the pointwise growth rate gamma = exp(-p)
% and the flow direction (u, v)/max|u| on an n-by-n grid over the disk scaled
% to unit radius (values outside the disk are those at its edge), with the
% roughness tensor K*, J* and growth rate |dOmega/dt|/|Omega|. The
% two-dimensional wave h = a sin(2 pi xi') sin(2 pi eta') has an isotropic
% K* with J* K* = 1, so on the unit disk its solution is the flat one at
% every a; one frame (a = 0) is stored for it, with its growth rates.
% Writes docs/assets/roughness.js defining window.ROUGHNESS with the grids
% as base64: gamma as uint8, round(255 (gamma - 0.8)/0.2) (the colour range
% of Fig. 5); u and v as int8, round(127 u/max|u|).

lambdaR = 1;
aR = linspace(0, 1, 31);
n = 48;
xg = linspace(-1, 1, n);
[Xg, Yg] = meshgrid(xg, xg);              % row j is y = xg(j), column i is x = xg(i)
rho = hypot(Xg, Yg);
Xc = Xg ./ max(rho, 1);  Yc = Yg ./ max(rho, 1);   % clamp to the disk

wave1 = cell(numel(aR), 1);
rate2 = zeros(size(aR));  K2 = zeros(numel(aR), 2);  J2 = zeros(size(aR));
warning('off', 'MATLAB:scatteredInterpolant:DupPtsAvValuesWarnId');
for k = 1:numel(aR)
  a = aR(k);
  fprintf('roughness a = %.3f (%d/%d)\n', a, k, numel(aR))

  [K, J] = roughnessTensor(@(x, y) a * sin(2*pi*x));
  [dA, u, v, p, xc, yc] = growthHomogenized(lambdaR, K, J);
  Rd = 1 / sqrt(J);
  fG = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, exp(-lambdaR * p(:)));
  fU = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, u(:));
  fV = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, v(:));
  G = fG(Xc, Yc);  U = fU(Xc, Yc);  V = fV(Xc, Yc);
  s = max(hypot(U(:), V(:)));
  wave1{k} = struct('a', a, 'rate', round(dA / pi, 5), ...
    'K', round([K(1,1) K(2,2)], 5), 'J', round(J, 5), ...
    'gamma', encodeU8(G), 'u', encodeI8(U / s), 'v', encodeI8(V / s));

  [K, J] = roughnessTensor(@(x, y) a * sin(2*pi*x) .* sin(2*pi*y));
  rate2(k) = growthHomogenized(lambdaR, K, J) / pi;
  K2(k, :) = [K(1,1) K(2,2)];  J2(k) = J;
  if k == 1
    [~, u, v, p, xc, yc] = growthHomogenized(lambdaR, K, J);
    Rd = 1 / sqrt(J);
    fG = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, exp(-lambdaR * p(:)));
    fU = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, u(:));
    fV = scatteredInterpolant(xc(:) / Rd, yc(:) / Rd, v(:));
    G = fG(Xc, Yc);  U = fU(Xc, Yc);  V = fV(Xc, Yc);
    s = max(hypot(U(:), V(:)));
    flat = struct('gamma', encodeU8(G), 'u', encodeI8(U / s), 'v', encodeI8(V / s));
  end
end
warning('on', 'MATLAB:scatteredInterpolant:DupPtsAvValuesWarnId');

out = struct('n', n, 'lambda', lambdaR, 'a', aR, 'gammaRange', [0.8 1], ...
  'wave1', {wave1}, 'flat', flat, ...
  'wave2', struct('rate', round(rate2, 5), 'K', round(K2, 5), 'J', round(J2, 5)), ...
  'algae', round(cmocean('algae', 32), 4));
fid = fopen(fullfile(here, 'assets', 'roughness.js'), 'w');
fprintf(fid, '// Generated by docs/makeinteractive.m: homogenized growth on periodic surfaces.\n');
fprintf(fid, 'window.ROUGHNESS = %s;\n', jsonencode(out));
fclose(fid);


% ── Moving boundary on periodic surfaces (interactive Fig. 6) ────────────────
% The committed simulations of Fig. 6 (data/fig6/*.mat, from
% scripts/movingBoundaryRoughness.m): at every time step the boundary of the
% homogenized domain, at physical scale (sqrt(J*) times the reference
% coordinates, as in figs/scripts/fig6.m), and the area relative to the
% initial area. Writes docs/assets/moving-boundary.js defining
% window.MOVING_BOUNDARY = { iso, aniso, algae }, each run with t, area and
% boundaries (one [x1 y1 x2 y2 ...] list per time step).

runsMB = struct();
for nm = {'isotropic', 'anisotropic'}
  M = load(fullfile(root, 'data', 'fig6', [nm{1} '.mat']));
  sJ = sqrt(M.J);
  bnd = cell(numel(M.Xb), 1);
  for k = 1:numel(M.Xb)
    xy = sJ * [vertcat(M.Xb{k}{:}), vertcat(M.Yb{k}{:})];
    keep = [true; any(abs(diff(xy)) > 1e-9, 2)];      % drop repeated element corners
    xy = xy(keep, :);
    bnd{k} = round(reshape(xy.', 1, []), 4);
  end
  r = struct('t', round(M.AA(:, 1)', 4), 'area', round(M.AA(:, 2)' / M.A0, 4), ...
             'boundaries', {bnd});
  if strcmp(nm{1}, 'isotropic'), runsMB.iso = r; else, runsMB.aniso = r; end
end
fid = fopen(fullfile(here, 'assets', 'moving-boundary.js'), 'w');
fprintf(fid, '// Generated by docs/makeinteractive.m: moving boundaries of Fig. 6.\n');
fprintf(fid, 'window.MOVING_BOUNDARY = %s;\n', jsonencode(struct('iso', runsMB.iso, 'aniso', runsMB.aniso, ...
  'algae', round(cmocean('algae', 32), 4))));
fclose(fid);


% ── Pressure and velocity on spheres of different radii (interactive Fig. 2) ──
% As scripts/sphereProfiles.m: the cap H = pi/2 with lambda = 1 on spheres of
% radius R = 10, 11, ..., 42, giving the pressure p and polar velocity u on a
% grid of the polar angle eta in [0, pi/2], clustered at the edge where the
% velocity rises steeply (the page mirrors them to
% [-pi/2, pi/2] as in Fig. 2). Writes docs/assets/sphere-profiles.js defining
% window.SPHERE_PROFILES = { eta, R, p, u, paperR }.

Rp = 10:42;
etaP = pi/2 * sin(pi/2 * linspace(0, 1, 121));   % clustered at the edge, where u is steep
Pp = zeros(numel(Rp), numel(etaP));  Up = Pp;
for k = 1:numel(Rp)
  [~, p, h, u] = growthSphere(pi/2, 1, Rp(k), 100);
  Pp(k, :) = interp1(h, p, etaP, 'pchip');
  Up(k, :) = interp1(h, u, etaP, 'pchip');
end
out = struct('eta', round(etaP, 5), 'R', Rp, 'p', round(Pp, 4), 'u', round(Up, 5), ...
             'paperR', 10 + [0, 2.^(1:5)]);
fid = fopen(fullfile(here, 'assets', 'sphere-profiles.js'), 'w');
fprintf(fid, '// Generated by docs/makeinteractive.m: pressure and velocity on spheres, H = pi/2.\n');
fprintf(fid, 'window.SPHERE_PROFILES = %s;\n', jsonencode(out));
fclose(fid);


function s = encodeU8(G)
% gamma in [0.8, 1] -> uint8, row-major (x fastest), base64
  q = uint8(round(255 * min(max((G - 0.8) / 0.2, 0), 1)));
  s = matlab.net.base64encode(reshape(q.', 1, []));
end

function s = encodeI8(U)
% values in [-1, 1] -> int8 stored as bytes, row-major (x fastest), base64
  q = int8(round(127 * min(max(U, -1), 1)));
  s = matlab.net.base64encode(typecast(reshape(q.', 1, []), 'uint8'));
end
